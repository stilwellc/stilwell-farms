#!/usr/bin/env python3
"""Stilwell Farms town routes: the named spots townsfolk walk between, and a flow field per spot.

Runs after gen_art.py (it reads the town's walkability from the generated src/maps.c) and writes
  src/routes.h   SP_* spot ids, NUM_SPOTS, accessors
  src/routes.c   (banked) spot coordinates + one 2-bit direction per town cell per spot

A townsperson heading for spot s just looks up route_dir(s, x, y) at every cell and steps that way:
no pathfinding on the Game Boy, and every spot is reachable from every walkable cell.
"""
import os, re, sys
from collections import deque

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name, x, y   (each must be a walkable town cell; keep shop doors clear of the cells players stand on)
SPOTS = [
    ('STORE', 12, 4),     # Rosa's counter, beside the General Store door (players use x 10-11)
    ('SMITH', 5, 4),      # Brick's forge (players use x 2-4)
    ('CAFE', 22, 4),      # Ada's cafe (players use x 19-21)
    ('CARP', 29, 4),      # June's carpentry (players use x 26-28)
    ('HALL', 18, 9),      # Mayor Hollis at the town hall steps (players use x 14-17)
    ('FOUNT_W', 13, 13),  # plaza, west of the fountain
    ('FOUNT_E', 18, 13),  # plaza, east of the fountain
    ('CAFE_T1', 19, 5),   # cafe terrace seats
    ('CAFE_T2', 20, 5),
    ('CAFE_T3', 23, 5),
    ('CAFE_T4', 21, 5),
    ('PARK_W', 12, 18),   # the park by the west bench
    ('PARK_E', 19, 18),   # by the east bench
    ('PARK_S', 16, 19),   # the park lawn
    ('PARK_C', 15, 17),   # park path
    ('GARDEN', 4, 11),    # the town vegetable garden gate
    ('ORCHARD', 26, 10),  # under the east orchard trees
    ('HOME_A', 4, 14),    # Ada and Milo's house door
    ('HOME_B', 28, 14),   # Mayor Hollis's house door
    ('BOARD', 12, 9),     # beside the notice board
    ('ROAD', 17, 2),      # beside the farm road (clear of where you walk in)
    ('MARKET', 11, 8),    # under the market tent
    ('PLAZA_1', 12, 10),  # festival spots around the fountain
    ('PLAZA_2', 19, 10),
    ('PLAZA_3', 13, 14),
    ('PLAZA_4', 18, 14),
    ('PLAZA_5', 13, 11),
    # Market Street (invest.c remaps some stops here once it is open: see townlife.c tl_spot)
    ('MKT_W', 10, 26),    # the west lots
    ('MKT_E', 19, 27),    # the east lots
    ('BAND', 14, 27),     # before the bandstand
    ('PLAYGND', 5, 28),   # by the playground
]
DIRS = [(0, 1), (0, -1), (-1, 0), (1, 0)]   # D_DOWN, D_UP, D_LEFT, D_RIGHT


def main():
    maps_h = open(os.path.join(ROOT, 'src/maps.h')).read()
    town = int(re.search(r'#define MAP_TOWN (\d+)', maps_h).group(1))
    src = open(os.path.join(ROOT, 'src/maps.c')).read()
    kind = [int(v) for v in re.search(r'm%d_kind\[\d+\] = \{([^}]*)\}' % town, src).group(1).split(',')]
    W = 32   # the town is 32 wide, so its rows are stored at a 32-cell stride
    H = len(kind) // 32
    walk = lambda x, y: 0 <= x < W and 0 <= y < H and y * 32 + x < len(kind) and kind[y * 32 + x] & 1
    out_h = ['// generated by tools/gen_routes.py -- do not edit', '#ifndef ROUTES_H', '#define ROUTES_H',
             '#include <gb/gb.h>', '#include <stdint.h>']
    for k, (n, x, y) in enumerate(SPOTS):
        if not walk(x, y):
            sys.exit(f'gen_routes: spot {n} ({x},{y}) is not walkable')
        out_h.append(f'#define SP_{n} {k}')
    out_h += [f'#define NUM_SPOTS {len(SPOTS)}',
              'uint8_t spot_x(uint8_t s) BANKED;',
              'uint8_t spot_y(uint8_t s) BANKED;',
              'uint8_t route_dir(uint8_t s, uint8_t x, uint8_t y) BANKED;   // D_* toward spot s from (x, y)',
              '#endif', '']
    rows = []
    for n, sx, sy in SPOTS:
        dist = {(sx, sy): 0}
        q = deque([(sx, sy)])
        while q:
            c = q.popleft()
            for dx, dy in DIRS:
                nb = (c[0] + dx, c[1] + dy)
                if nb not in dist and walk(*nb):
                    dist[nb] = dist[c] + 1
                    q.append(nb)
        bits = [0] * (W * H)
        for (x, y), d in dist.items():
            if not d:
                continue
            best = None
            for k, (dx, dy) in enumerate(DIRS):
                nd = dist.get((x + dx, y + dy))
                if nd is not None and nd == d - 1:
                    # prefer the long street rows (y 4-5, 15): fewer zig-zags through the plaza
                    score = (0 if dx else 1) if y in (4, 5, 15) else (1 if dx else 0)
                    if best is None or score < best[0]:
                        best = (score, k)
            bits[y * 32 + x] = best[1]
        unreached = [(x, y) for y in range(H) for x in range(W) if walk(x, y) and (x, y) not in dist]
        if unreached and n == SPOTS[0][0]:   # sealed pockets (e.g. between two storefronts) nobody can reach
            print(f'gen_routes: note: {len(unreached)} sealed walkable cell(s), e.g. {unreached[:3]}', file=sys.stderr)
        packed = [bits[i] | bits[i + 1] << 2 | bits[i + 2] << 4 | bits[i + 3] << 6 for i in range(0, W * H, 4)]
        rows.append('{' + ','.join(str(b) for b in packed) + '}')
    out_c = ['// generated by tools/gen_routes.py -- do not edit', '#pragma bank 255', '#include <gb/gb.h>',
             '#include <stdint.h>', '#include "routes.h"', 'BANKREF(route_dir)',
             'static const uint8_t sx[NUM_SPOTS] = {%s};' % ','.join(str(s[1]) for s in SPOTS),
             'static const uint8_t sy[NUM_SPOTS] = {%s};' % ','.join(str(s[2]) for s in SPOTS),
             f'static const uint8_t field[NUM_SPOTS][{W * H // 4}] = {{\n' + ',\n'.join(rows) + '};',
             'uint8_t spot_x(uint8_t s) BANKED { return sx[s]; }',
             'uint8_t spot_y(uint8_t s) BANKED { return sy[s]; }',
             'uint8_t route_dir(uint8_t s, uint8_t x, uint8_t y) BANKED {',
             '    uint8_t i = (uint8_t)(x >> 2) | (uint8_t)(y << 3);',
             '    return (field[s][i] >> ((x & 3) << 1)) & 3;',
             '}', '']
    open(os.path.join(ROOT, 'src/routes.h'), 'w').write('\n'.join(out_h))
    open(os.path.join(ROOT, 'src/routes.c'), 'w').write('\n'.join(out_c))
    print(f'gen_routes: {len(SPOTS)} spots, {len(SPOTS) * W * H // 4} bytes of flow fields')


if __name__ == '__main__':
    main()
